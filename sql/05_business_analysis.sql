-- CORE BUSINESS ANALYSIS ON THE ANALYTICS SCHEMA.
-- 1 OVERALL KPIS
-- REVENUE = SUM(PRICE) OF DELIVERED ORDERS (FREIGHT EXCLUDED).
SELECT
  COUNT(*) AS DELIVERED_ORDERS,
  ROUND(SUM(ITEMS_REVENUE), 2) AS TOTAL_REVENUE,
  ROUND(SUM(ITEMS_REVENUE) / COUNT(*), 2) AS AVG_ORDER_VALUE,
  ROUND(AVG(REVIEW_SCORE), 2) AS AVG_REVIEW_SCORE,
  ROUND(AVG(DELIVERY_DAYS), 1) AS AVG_DELIVERY_DAYS,
  ROUND(100.0 * COUNT(*) FILTER (WHERE IS_LATE) / COUNT(*), 2) AS LATE_DELIVERY_PCT
FROM ANALYTICS.FACT_ORDERS
WHERE IS_DELIVERED;
-- 96,478 delivered orders generated 13.22M in revenue; AOV 137.04, avg review 4.16, avg delivery 12.5 days, 6.77% orders delivered late


-- 2 MONTHLY REVENUE TREND WITH MONTH-OVER-MONTH GROWTH
-- SEP-DEC 2016 AND SEP-OCT 2018 EXCLUDED: VERY FEW ORDERS
WITH MONTHLY AS (
  SELECT D.YEAR_MONTH,
         COUNT(*) AS ORDERS,
         SUM(F.ITEMS_REVENUE) AS REVENUE
  FROM ANALYTICS.FACT_ORDERS F
  JOIN ANALYTICS.DIM_DATE D ON F.PURCHASE_DATE = D.DATE_KEY
  WHERE F.IS_DELIVERED
    AND D.YEAR_MONTH BETWEEN '2017-01' AND '2018-08'
  GROUP BY D.YEAR_MONTH
)
SELECT YEAR_MONTH,
       ORDERS,
       ROUND(REVENUE, 2) AS REVENUE,
       ROUND(100.0 * (REVENUE - LAG(REVENUE) OVER (ORDER BY YEAR_MONTH))
             / NULLIF(LAG(REVENUE) OVER (ORDER BY YEAR_MONTH), 0), 2) AS MOM_GROWTH_PCT
FROM MONTHLY
ORDER BY YEAR_MONTH;
-- Revenue grew from 111.8K (Jan 2017) to 489.3K (May 2017); growth is volatile month to month (Feb +109.5%, Apr -5.2%, Jun -13.8%). Early-2017 growth is partly a small-base effect


-- 3 TOP 10 CATEGORIES BY REVENUE WITH % SHARE
WITH CAT AS (
  SELECT P.CATEGORY,
         SUM(I.PRICE) AS REVENUE,
         COUNT(DISTINCT I.ORDER_ID) AS ORDERS
  FROM ANALYTICS.FACT_ORDER_ITEMS I
  JOIN ANALYTICS.DIM_PRODUCTS P ON I.PRODUCT_ID = P.PRODUCT_ID
  WHERE I.IS_DELIVERED
  GROUP BY P.CATEGORY
)
SELECT RANK() OVER (ORDER BY REVENUE DESC) AS RNK,
       CATEGORY,
       ORDERS,
       ROUND(REVENUE, 2) AS REVENUE,
       ROUND(100.0 * REVENUE / SUM(REVENUE) OVER (), 2) AS REVENUE_SHARE_PCT
FROM CAT
ORDER BY REVENUE DESC
LIMIT 10;
-- health_beauty (9.33%), watches_gifts (8.82%), bed_bath_table (7.74%), sports_leisure (7.22%) and computers_accessories (6.72%) lead; top 6 categories together are ~45% of revenue


-- 4 STATE-WISE PERFORMANCE (CUSTOMERS, ORDERS, REVENUE, AOV)
SELECT C.STATE,
       COUNT(DISTINCT C.CUSTOMER_UNIQUE_ID) AS CUSTOMERS,
       COUNT(*) AS ORDERS,
       ROUND(SUM(F.ITEMS_REVENUE), 2) AS REVENUE,
       ROUND(SUM(F.ITEMS_REVENUE) / COUNT(*), 2) AS AVG_ORDER_VALUE,
       ROUND(AVG(F.DELIVERY_DAYS), 1) AS AVG_DELIVERY_DAYS
FROM ANALYTICS.FACT_ORDERS F
JOIN ANALYTICS.DIM_CUSTOMERS C ON F.CUSTOMER_ID = C.CUSTOMER_ID
WHERE F.IS_DELIVERED
GROUP BY C.STATE
ORDER BY REVENUE DESC;
-- Sao Paulo (SP) is the biggest market: 40,501 orders, 5.07M revenue (~38% of total), fastest delivery at 8.7 days


-- 5 DOES LATE DELIVERY AFFECT REVIEW SCORES?
SELECT CASE WHEN IS_LATE THEN 'Late' ELSE 'On time / early' END AS DELIVERY_STATUS,
       COUNT(*) AS ORDERS,
       ROUND(AVG(REVIEW_SCORE), 2) AS AVG_REVIEW_SCORE,
       ROUND(100.0 * COUNT(*) FILTER (WHERE REVIEW_SCORE <= 2) / COUNT(*), 2) AS PCT_BAD_REVIEWS
FROM ANALYTICS.FACT_ORDERS
WHERE IS_DELIVERED
  AND IS_LATE IS NOT NULL
  AND REVIEW_SCORE IS NOT NULL
GROUP BY IS_LATE;
-- Late orders average 2.27 review score vs 4.29 for on-time orders; 62.42% of late orders get a bad review (score <= 2) vs 9.27% for on-time


-- 6 REVIEW SCORE BY DELAY BUCKET
SELECT CASE
         WHEN DELAY_DAYS <= 0 THEN '1. On time / early'
         WHEN DELAY_DAYS <= 3 THEN '2. 1-3 days late'
         WHEN DELAY_DAYS <= 7 THEN '3. 4-7 days late'
         ELSE                       '4. 8+ days late'
       END AS DELAY_BUCKET,
       COUNT(*) AS ORDERS,
       ROUND(AVG(REVIEW_SCORE), 2) AS AVG_REVIEW_SCORE
FROM ANALYTICS.FACT_ORDERS
WHERE IS_DELIVERED
  AND DELAY_DAYS IS NOT NULL
  AND REVIEW_SCORE IS NOT NULL
GROUP BY 1
ORDER BY 1;
-- Review score falls steadily as delay grows: 4.29 (on time) -> 3.29 (1-3 days late) -> 2.10 (4-7 days) -> 1.70 (8+ days). The 8+ days group is the largest late bucket (2,781 orders)


-- 7 SLOWEST STATES FOR DELIVERY (LATE % AND AVG DAYS)
SELECT C.STATE,
       COUNT(*) AS ORDERS,
       ROUND(AVG(F.DELIVERY_DAYS), 1) AS AVG_DELIVERY_DAYS,
       ROUND(100.0 * COUNT(*) FILTER (WHERE F.IS_LATE) / COUNT(*), 2) AS LATE_PCT
FROM ANALYTICS.FACT_ORDERS F
JOIN ANALYTICS.DIM_CUSTOMERS C ON F.CUSTOMER_ID = C.CUSTOMER_ID
WHERE F.IS_DELIVERED AND F.IS_LATE IS NOT NULL
GROUP BY C.STATE
HAVING COUNT(*) >= 100
ORDER BY LATE_PCT DESC;
-- Northeast states have the worst delivery performance: AL has 21.41% late orders (24.5 avg days), followed by MA (17.43%), SE (15.22%), PI (13.87%) and CE (13.76%). PA has the longest avg delivery time at 23.7 days. RJ stands out by volume: 12,350 orders with 12.11% late


-- 8 TOP 20 SELLERS WITH CUMULATIVE REVENUE SHARE (PARETO)
WITH S AS (
  SELECT SELLER_ID,
         SUM(PRICE) AS REVENUE,
         COUNT(DISTINCT ORDER_ID) AS ORDERS
  FROM ANALYTICS.FACT_ORDER_ITEMS
  WHERE IS_DELIVERED
  GROUP BY SELLER_ID
)
SELECT RANK() OVER (ORDER BY REVENUE DESC) AS RNK,
       S.SELLER_ID,
       D.CITY,
       D.STATE,
       S.ORDERS,
       ROUND(S.REVENUE, 2) AS REVENUE,
       ROUND(100.0 * SUM(S.REVENUE) OVER (ORDER BY S.REVENUE DESC)
             / SUM(S.REVENUE) OVER (), 2) AS CUMULATIVE_SHARE_PCT
FROM S
JOIN ANALYTICS.DIM_SELLERS D ON S.SELLER_ID = D.SELLER_ID
ORDER BY REVENUE DESC
LIMIT 20;
-- Top seller (Guariba, SP) earns 226,988 (1.72% of revenue); top 9 sellers together contribute 12.28%, and most top sellers are based in SP


-- 9 SELLERS WITH THE WORST LATE-DELIVERY RATE (MIN 50 ORDERS)
SELECT I.SELLER_ID,
       COUNT(DISTINCT I.ORDER_ID) AS ORDERS,
       ROUND(100.0 * COUNT(DISTINCT I.ORDER_ID) FILTER (WHERE F.IS_LATE)
             / COUNT(DISTINCT I.ORDER_ID), 2) AS LATE_PCT,
       ROUND(AVG(F.REVIEW_SCORE), 2) AS AVG_REVIEW_SCORE
FROM ANALYTICS.FACT_ORDER_ITEMS I
JOIN ANALYTICS.FACT_ORDERS F ON I.ORDER_ID = F.ORDER_ID
WHERE I.IS_DELIVERED AND F.IS_LATE IS NOT NULL
GROUP BY I.SELLER_ID
HAVING COUNT(DISTINCT I.ORDER_ID) >= 50
ORDER BY LATE_PCT DESC
LIMIT 10;
-- Among sellers with 50+ orders, the worst late rate is 30.14% (73 orders, avg review 3.07); another 389-order seller has 19.02% late rate, so a high-volume seller is also a delivery risk


-- 10 PAYMENT TYPE ANALYSIS
SELECT MAIN_PAYMENT_TYPE,
       COUNT(*) AS ORDERS,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS ORDER_SHARE_PCT,
       ROUND(AVG(PAYMENT_TOTAL), 2) AS AVG_PAYMENT,
       ROUND(AVG(MAX_INSTALLMENTS), 1) AS AVG_INSTALLMENTS
FROM ANALYTICS.FACT_ORDERS
WHERE IS_DELIVERED AND MAIN_PAYMENT_TYPE IS NOT NULL
GROUP BY MAIN_PAYMENT_TYPE
ORDER BY ORDERS DESC;
-- Credit card dominates with 75.48% of orders (avg payment 166.18, 3.5 installments), followed by boleto (19.89%), voucher (3.09%) and debit card (1.54%). Credit card orders have the highest average value


-- 11 REPEAT CUSTOMER RATE (BY UNIQUE CUSTOMER)
WITH CUST AS (
  SELECT C.CUSTOMER_UNIQUE_ID,
         COUNT(*) AS ORDERS
  FROM ANALYTICS.FACT_ORDERS F
  JOIN ANALYTICS.DIM_CUSTOMERS C ON F.CUSTOMER_ID = C.CUSTOMER_ID
  WHERE F.IS_DELIVERED
  GROUP BY C.CUSTOMER_UNIQUE_ID
)
SELECT COUNT(*) AS UNIQUE_CUSTOMERS,
       COUNT(*) FILTER (WHERE ORDERS > 1) AS REPEAT_CUSTOMERS,
       ROUND(100.0 * COUNT(*) FILTER (WHERE ORDERS > 1) / COUNT(*), 2) AS REPEAT_RATE_PCT
FROM CUST;
-- Only 3.00% of customers (2,801 of 93,358 unique customers) placed more than one delivered order, so ~97% are one-time buyers. Retention is a major growth opportunity


-- 12 WEEKDAY VS WEEKEND ORDERING PATTERN
SELECT D.DAY_NAME,
       D.DAY_OF_WEEK_NUM,
       COUNT(*) AS ORDERS,
       ROUND(SUM(F.ITEMS_REVENUE), 2) AS REVENUE
FROM ANALYTICS.FACT_ORDERS F
JOIN ANALYTICS.DIM_DATE D ON F.PURCHASE_DATE = D.DATE_KEY
WHERE F.IS_DELIVERED
GROUP BY D.DAY_NAME, D.DAY_OF_WEEK_NUM
ORDER BY D.DAY_OF_WEEK_NUM;
-- Orders peak on Monday (15,701) and decline through the week to Friday (13,685); Saturday is the lowest day (10,555 orders, 1.46M revenue). Weekends contribute ~23% of orders and revenue, and a weekday sees ~34% more orders than a weekend day on average


