CREATE TABLE RAW.CUSTOMERS (
    CUSTOMER_ID VARCHAR(50) PRIMARY KEY,
    CUSTOMER_UNIQUE_ID VARCHAR(50),
    CUSTOMER_ZIP_CODE_PREFIX VARCHAR(10),
    CUSTOMER_CITY VARCHAR(100),
    CUSTOMER_STATE VARCHAR(5)
);

CREATE TABLE RAW.GEOLOCATION (
    GEOLOCATION_ZIP_CODE_PREFIX VARCHAR(10),
    GEOLOCATION_LAT NUMERIC(18,15),
    GEOLOCATION_LNG NUMERIC(18,15),
    GEOLOCATION_CITY VARCHAR(100),
    GEOLOCATION_STATE VARCHAR(5)
);

CREATE TABLE RAW.ORDERS (
    ORDER_ID VARCHAR(50) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(50),
    ORDER_STATUS VARCHAR(20),
    ORDER_PURCHASE_TIMESTAMP TIMESTAMP,
    ORDER_APPROVED_AT TIMESTAMP,
    ORDER_DELIVERED_CARRIER_DATE TIMESTAMP,
    ORDER_DELIVERED_CUSTOMER_DATE TIMESTAMP,
    ORDER_ESTIMATED_DELIVERY_DATE TIMESTAMP
);

CREATE TABLE RAW.ORDER_ITEMS (
    ORDER_ID VARCHAR(50),
    ORDER_ITEM_ID INT,
    PRODUCT_ID VARCHAR(50),
    SELLER_ID VARCHAR(50),
    SHIPPING_LIMIT_DATE TIMESTAMP,
    PRICE NUMERIC(10,2),
    FREIGHT_VALUE NUMERIC(10,2),
    PRIMARY KEY (ORDER_ID, ORDER_ITEM_ID)
);

CREATE TABLE RAW.ORDER_PAYMENTS (
    ORDER_ID VARCHAR(50),
    PAYMENT_SEQUENTIAL INT,
    PAYMENT_TYPE VARCHAR(30),
    PAYMENT_INSTALLMENTS INT,
    PAYMENT_VALUE NUMERIC(10,2)
);

CREATE TABLE RAW.ORDER_REVIEWS (
    REVIEW_ID VARCHAR(50),
    ORDER_ID VARCHAR(50),
    REVIEW_SCORE INT,
    REVIEW_COMMENT_TITLE TEXT,
    REVIEW_COMMENT_MESSAGE TEXT,
    REVIEW_CREATION_DATE TIMESTAMP,
    REVIEW_ANSWER_TIMESTAMP TIMESTAMP
);

CREATE TABLE RAW.PRODUCTS (
    PRODUCT_ID VARCHAR(50) PRIMARY KEY,
    PRODUCT_CATEGORY_NAME VARCHAR(100),
    PRODUCT_NAME_LENGHT INT,
    PRODUCT_DESCRIPTION_LENGHT INT,
    PRODUCT_PHOTOS_QTY INT,
    PRODUCT_WEIGHT_G INT,
    PRODUCT_LENGTH_CM INT,
    PRODUCT_HEIGHT_CM INT,
    PRODUCT_WIDTH_CM INT
);

CREATE TABLE RAW.SELLERS (
    SELLER_ID VARCHAR(50) PRIMARY KEY,
    SELLER_ZIP_CODE_PREFIX VARCHAR(10),
    SELLER_CITY VARCHAR(100),
    SELLER_STATE VARCHAR(5)
);

CREATE TABLE RAW.PRODUCT_CATEGORY_TRANSLATION (
    PRODUCT_CATEGORY_NAME VARCHAR(100),
    PRODUCT_CATEGORY_NAME_ENGLISH VARCHAR(100)
);

--FOR VERIFYING IMPORTED DATA
SELECT 'CUSTOMERS' AS TBL, COUNT(*) FROM RAW.CUSTOMERS
UNION ALL SELECT 'GEOLOCATION', COUNT(*) FROM RAW.GEOLOCATION
UNION ALL SELECT 'ORDERS', COUNT(*) FROM RAW.ORDERS
UNION ALL SELECT 'ORDER_ITEMS', COUNT(*) FROM RAW.ORDER_ITEMS
UNION ALL SELECT 'ORDER_PAYMENTS', COUNT(*) FROM RAW.ORDER_PAYMENTS
UNION ALL SELECT 'ORDER_REVIEWS', COUNT(*) FROM RAW.ORDER_REVIEWS
UNION ALL SELECT 'PRODUCTS', COUNT(*) FROM RAW.PRODUCTS
UNION ALL SELECT 'SELLERS', COUNT(*) FROM RAW.SELLERS
UNION ALL SELECT 'CATEGORY_TRANSLATION', COUNT(*) FROM RAW.PRODUCT_CATEGORY_TRANSLATION;


