-- ORDERS: HOW MANY DATES ARE MISSING
SELECT
  COUNT(*) AS TOTAL_ORDERS,
  COUNT(*) FILTER (WHERE ORDER_APPROVED_AT IS NULL) AS NULL_APPROVED,
  COUNT(*) FILTER (WHERE ORDER_DELIVERED_CARRIER_DATE IS NULL) AS NULL_CARRIER_DATE,
  COUNT(*) FILTER (WHERE ORDER_DELIVERED_CUSTOMER_DATE IS NULL) AS NULL_DELIVERED_DATE
FROM RAW.ORDERS;

-- PRODUCTS: MISSING CATEGORY / DIMENSIONS
SELECT
  COUNT(*) AS TOTAL_PRODUCTS,
  COUNT(*) FILTER (WHERE PRODUCT_CATEGORY_NAME IS NULL) AS NULL_CATEGORY,
  COUNT(*) FILTER (WHERE PRODUCT_WEIGHT_G IS NULL) AS NULL_WEIGHT
FROM RAW.PRODUCTS;

SELECT ORDER_STATUS,
       COUNT(*) AS ORDERS,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM RAW.ORDERS
GROUP BY ORDER_STATUS
ORDER BY ORDERS DESC;

-- REVIEWS: SAME REVIEW_ID HOW MANY TIMES
SELECT COUNT(*) AS DUPLICATE_REVIEW_IDS
FROM (
  SELECT REVIEW_ID FROM RAW.ORDER_REVIEWS
  GROUP BY REVIEW_ID HAVING COUNT(*) > 1
) D;

-- REVIEWS: DOES AN ORDER HAVE MULTIPLE REVIEWS
SELECT COUNT(*) AS ORDERS_WITH_MULTIPLE_REVIEWS
FROM (
  SELECT ORDER_ID FROM RAW.ORDER_REVIEWS
  GROUP BY ORDER_ID HAVING COUNT(*) > 1
) D;

-- GEOLOCATION: HOW MANY RECORDS FOR ONE ZIP
SELECT COUNT(*) AS TOTAL_ROWS,
       COUNT(DISTINCT GEOLOCATION_ZIP_CODE_PREFIX) AS UNIQUE_ZIPS
FROM RAW.GEOLOCATION;

-- ORDERS WHOSE CUSTOMERS ARE UNKNOWN
SELECT COUNT(*) AS ORDERS_WITHOUT_CUSTOMER
FROM RAW.ORDERS O
LEFT JOIN RAW.CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;

-- ORDER ITEMS WHOSE ORDER NOT FOUND
SELECT COUNT(*) AS ITEMS_WITHOUT_ORDER
FROM RAW.ORDER_ITEMS OI
LEFT JOIN RAW.ORDERS O ON OI.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID IS NULL;

-- ORDER ITEMS WHOSE PRODUCT NOT FOUND
SELECT COUNT(*) AS ITEMS_WITHOUT_PRODUCT
FROM RAW.ORDER_ITEMS OI
LEFT JOIN RAW.PRODUCTS P ON OI.PRODUCT_ID = P.PRODUCT_ID
WHERE P.PRODUCT_ID IS NULL;

-- PRODUCT CATEGORIES WHOSE ENGLISH TRANSLATION IS MISSING 
SELECT DISTINCT P.PRODUCT_CATEGORY_NAME
FROM RAW.PRODUCTS P
LEFT JOIN RAW.PRODUCT_CATEGORY_TRANSLATION T
       ON P.PRODUCT_CATEGORY_NAME = T.PRODUCT_CATEGORY_NAME
WHERE T.PRODUCT_CATEGORY_NAME IS NULL
  AND P.PRODUCT_CATEGORY_NAME IS NOT NULL;

-- ORDERS WITH NO ITEMS
SELECT COUNT(*) AS ORDERS_WITHOUT_ITEMS
FROM RAW.ORDERS O
LEFT JOIN RAW.ORDER_ITEMS OI ON O.ORDER_ID = OI.ORDER_ID
WHERE OI.ORDER_ID IS NULL;

-- ORDERS WHOSE ORDER IS DELIVERED BUT DELIVERY DATE IS NULL
SELECT COUNT(*) AS DELIVERED_BUT_NO_DATE
FROM RAW.ORDERS
WHERE ORDER_STATUS = 'DELIVERED' AND ORDER_DELIVERED_CUSTOMER_DATE IS NULL;

-- ORDERS WHOSE DELIVERY DATE IS EARLIER THAN ITS PURCHASE DATE (WHICH IS IMPOSSIBLE)
SELECT COUNT(*) AS DELIVERED_BEFORE_PURCHASE
FROM RAW.ORDERS
WHERE ORDER_DELIVERED_CUSTOMER_DATE < ORDER_PURCHASE_TIMESTAMP;

-- INVALID VALUES
SELECT
  COUNT(*) FILTER (WHERE PRICE <= 0) AS NON_POSITIVE_PRICE,
  COUNT(*) FILTER (WHERE FREIGHT_VALUE < 0) AS NEGATIVE_FREIGHT
FROM RAW.ORDER_ITEMS;

SELECT COUNT(*) AS INVALID_REVIEW_SCORES
FROM RAW.ORDER_REVIEWS
WHERE REVIEW_SCORE NOT BETWEEN 1 AND 5;

SELECT COUNT(*) AS ZERO_PAYMENTS
FROM RAW.ORDER_PAYMENTS
WHERE PAYMENT_VALUE = 0;

SELECT MIN(ORDER_PURCHASE_TIMESTAMP) AS FIRST_ORDER,
       MAX(ORDER_PURCHASE_TIMESTAMP) AS LAST_ORDER
FROM RAW.ORDERS;

-- to check active sellers
SELECT COUNT(DISTINCT SELLER_ID) AS ACTIVE_SELLERS
FROM ANALYTICS.FACT_ORDER_ITEMS
WHERE IS_DELIVERED;