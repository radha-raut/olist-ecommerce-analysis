-- BUILDS THE ANALYTICS SCHEMA (STAR SCHEMA) FROM THE RAW TABLES.
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

-- HELPER: ONE ROW PER ZIP CODE (GEOLOCATION HAD ~1M DUPLICATES)
DROP TABLE IF EXISTS ANALYTICS.GEO_ZIP CASCADE;


CREATE TABLE ANALYTICS.GEO_ZIP AS
SELECT GEOLOCATION_ZIP_CODE_PREFIX AS ZIP_CODE,
       AVG(GEOLOCATION_LAT) AS LAT,
       AVG(GEOLOCATION_LNG) AS LNG
FROM RAW.GEOLOCATION
GROUP BY GEOLOCATION_ZIP_CODE_PREFIX;


-- DIM: CUSTOMERS
DROP TABLE IF EXISTS ANALYTICS.DIM_CUSTOMERS CASCADE;


CREATE TABLE ANALYTICS.DIM_CUSTOMERS AS
SELECT C.CUSTOMER_ID,
       C.CUSTOMER_UNIQUE_ID,
       INITCAP(C.CUSTOMER_CITY) AS CITY,
       UPPER(C.CUSTOMER_STATE)  AS STATE,
       C.CUSTOMER_ZIP_CODE_PREFIX AS ZIP_CODE,
       G.LAT,
       G.LNG
FROM RAW.CUSTOMERS C
LEFT JOIN ANALYTICS.GEO_ZIP G
       ON C.CUSTOMER_ZIP_CODE_PREFIX = G.ZIP_CODE;
ALTER TABLE ANALYTICS.DIM_CUSTOMERS ADD PRIMARY KEY (CUSTOMER_ID);


-- DIM: PRODUCTS (ENGLISH CATEGORY, 'UNKNOWN' FOR MISSING)
DROP TABLE IF EXISTS ANALYTICS.DIM_PRODUCTS CASCADE;


CREATE TABLE ANALYTICS.DIM_PRODUCTS AS
SELECT P.PRODUCT_ID,
       P.PRODUCT_CATEGORY_NAME AS CATEGORY_PT,
       COALESCE(
         T.PRODUCT_CATEGORY_NAME_ENGLISH,
         CASE P.PRODUCT_CATEGORY_NAME
           WHEN 'pc_gamer' THEN 'pc_gamer'
           WHEN 'portateis_cozinha_e_preparadores_de_alimentos'
                THEN 'portable_kitchen_food_preparers'
         END,
         'unknown'
       ) AS CATEGORY,
       P.PRODUCT_WEIGHT_G,
       P.PRODUCT_LENGTH_CM,
       P.PRODUCT_HEIGHT_CM,
       P.PRODUCT_WIDTH_CM,
       P.PRODUCT_PHOTOS_QTY
FROM RAW.PRODUCTS P
LEFT JOIN RAW.PRODUCT_CATEGORY_TRANSLATION T
       ON P.PRODUCT_CATEGORY_NAME = T.PRODUCT_CATEGORY_NAME;
ALTER TABLE ANALYTICS.DIM_PRODUCTS ADD PRIMARY KEY (PRODUCT_ID);


-- DIM: SELLERS
DROP TABLE IF EXISTS ANALYTICS.DIM_SELLERS CASCADE;


CREATE TABLE ANALYTICS.DIM_SELLERS AS
SELECT S.SELLER_ID,
       INITCAP(S.SELLER_CITY)  AS CITY,
       UPPER(S.SELLER_STATE)   AS STATE,
       S.SELLER_ZIP_CODE_PREFIX AS ZIP_CODE,
       G.LAT,
       G.LNG
FROM RAW.SELLERS S
LEFT JOIN ANALYTICS.GEO_ZIP G
       ON S.SELLER_ZIP_CODE_PREFIX = G.ZIP_CODE;
ALTER TABLE ANALYTICS.DIM_SELLERS ADD PRIMARY KEY (SELLER_ID);


-- DIM: DATE
DROP TABLE IF EXISTS ANALYTICS.DIM_DATE CASCADE;


CREATE TABLE ANALYTICS.DIM_DATE AS
SELECT D::DATE AS DATE_KEY,
       EXTRACT(YEAR FROM D)::INT AS YEAR,
       EXTRACT(QUARTER FROM D)::INT AS QUARTER,
       EXTRACT(MONTH FROM D)::INT AS MONTH_NUM,
       TO_CHAR(D, 'Mon') AS MONTH_NAME,
       TO_CHAR(D, 'YYYY-MM') AS YEAR_MONTH,
       EXTRACT(ISODOW FROM D)::INT AS DAY_OF_WEEK_NUM,
       TO_CHAR(D, 'Dy') AS DAY_NAME,
       (EXTRACT(ISODOW FROM D) IN (6,7)) AS IS_WEEKEND
FROM GENERATE_SERIES('2016-09-01'::date, '2018-12-31'::date, '1 day') AS D;
ALTER TABLE ANALYTICS.DIM_DATE ADD PRIMARY KEY (DATE_KEY);


-- FACT: ORDERS (GRAIN = 1 ROW PER ORDER)
DROP TABLE IF EXISTS ANALYTICS.FACT_ORDERS CASCADE;


CREATE TABLE ANALYTICS.FACT_ORDERS AS
WITH ITEMS AS (
    SELECT ORDER_ID,
           COUNT(*) AS ITEMS_COUNT,
           SUM(PRICE) AS ITEMS_REVENUE,
           SUM(FREIGHT_VALUE) AS FREIGHT_TOTAL
    FROM RAW.ORDER_ITEMS
    GROUP BY ORDER_ID
),
PAY AS (
    SELECT ORDER_ID,
           SUM(PAYMENT_VALUE) AS PAYMENT_TOTAL,
           MAX(PAYMENT_INSTALLMENTS) AS MAX_INSTALLMENTS
    FROM RAW.ORDER_PAYMENTS
    GROUP BY ORDER_ID
),
MAIN_PAY AS (
    SELECT DISTINCT ON (ORDER_ID) ORDER_ID, PAYMENT_TYPE
    FROM RAW.ORDER_PAYMENTS
    ORDER BY ORDER_ID, PAYMENT_VALUE DESC
),
REV AS (   -- LATEST REVIEW PER ORDER
    SELECT ORDER_ID, REVIEW_SCORE
    FROM (
        SELECT ORDER_ID, REVIEW_SCORE,
               ROW_NUMBER() OVER (
                   PARTITION BY ORDER_ID
                   ORDER BY REVIEW_ANSWER_TIMESTAMP DESC,
                            REVIEW_CREATION_DATE DESC) AS RN
        FROM RAW.ORDER_REVIEWS
    ) R
    WHERE RN = 1
)
SELECT O.ORDER_ID,
       O.CUSTOMER_ID,
       O.ORDER_STATUS,
       (O.ORDER_STATUS = 'delivered') AS IS_DELIVERED,
       O.ORDER_PURCHASE_TIMESTAMP::DATE AS PURCHASE_DATE,
       O.ORDER_PURCHASE_TIMESTAMP,
       O.ORDER_DELIVERED_CUSTOMER_DATE::DATE AS DELIVERED_DATE,
       O.ORDER_ESTIMATED_DELIVERY_DATE::DATE AS ESTIMATED_DATE,
       (O.ORDER_DELIVERED_CUSTOMER_DATE::DATE
          - O.ORDER_PURCHASE_TIMESTAMP::DATE) AS DELIVERY_DAYS,
       (O.ORDER_DELIVERED_CUSTOMER_DATE::DATE
          - O.ORDER_ESTIMATED_DELIVERY_DATE::DATE) AS DELAY_DAYS,
       CASE
         WHEN O.ORDER_DELIVERED_CUSTOMER_DATE IS NULL THEN NULL
         WHEN O.ORDER_DELIVERED_CUSTOMER_DATE::DATE
              > O.ORDER_ESTIMATED_DELIVERY_DATE::DATE THEN TRUE
         ELSE FALSE
       END AS IS_LATE,
       COALESCE(I.ITEMS_COUNT, 0) AS ITEMS_COUNT,
       COALESCE(I.ITEMS_REVENUE, 0) AS ITEMS_REVENUE,
       COALESCE(I.FREIGHT_TOTAL, 0) AS FREIGHT_TOTAL,
       COALESCE(P.PAYMENT_TOTAL, 0) AS PAYMENT_TOTAL,
       P.MAX_INSTALLMENTS,
       MP.PAYMENT_TYPE AS MAIN_PAYMENT_TYPE,
       R.REVIEW_SCORE
FROM RAW.ORDERS O
LEFT JOIN ITEMS I ON O.ORDER_ID = I.ORDER_ID
LEFT JOIN PAY P ON O.ORDER_ID = P.ORDER_ID
LEFT JOIN MAIN_PAY MP ON O.ORDER_ID = MP.ORDER_ID
LEFT JOIN REV R ON O.ORDER_ID = R.ORDER_ID;

ALTER TABLE ANALYTICS.FACT_ORDERS ADD PRIMARY KEY (ORDER_ID);

CREATE INDEX IDX_FO_CUSTOMER ON ANALYTICS.FACT_ORDERS (CUSTOMER_ID);
CREATE INDEX IDX_FO_DATE ON ANALYTICS.FACT_ORDERS (PURCHASE_DATE);


-- FACT: ORDER ITEMS (GRAIN = 1 ROW PER ITEM)
DROP TABLE IF EXISTS ANALYTICS.FACT_ORDER_ITEMS CASCADE;


CREATE TABLE ANALYTICS.FACT_ORDER_ITEMS AS
SELECT OI.ORDER_ID,
       OI.ORDER_ITEM_ID,
       OI.PRODUCT_ID,
       OI.SELLER_ID,
       O.CUSTOMER_ID,
       O.PURCHASE_DATE,
       O.ORDER_STATUS,
       O.IS_DELIVERED,
       OI.PRICE,
       OI.FREIGHT_VALUE,
       (OI.PRICE + OI.FREIGHT_VALUE) AS GROSS_VALUE
FROM RAW.ORDER_ITEMS OI
JOIN ANALYTICS.FACT_ORDERS O ON OI.ORDER_ID = O.ORDER_ID;



ALTER TABLE ANALYTICS.FACT_ORDER_ITEMS ADD PRIMARY KEY (ORDER_ID, ORDER_ITEM_ID);


CREATE INDEX IDX_FOI_PRODUCT ON ANALYTICS.FACT_ORDER_ITEMS (PRODUCT_ID);
CREATE INDEX IDX_FOI_SELLER  ON ANALYTICS.FACT_ORDER_ITEMS (SELLER_ID);

-- VALIDATION BY CHECKING ROW COUNTS
SELECT 'fact_orders' AS TBL, COUNT(*) FROM ANALYTICS.FACT_ORDERS
UNION ALL SELECT 'fact_order_items', COUNT(*) FROM ANALYTICS.FACT_ORDER_ITEMS
UNION ALL SELECT 'dim_customers', COUNT(*) FROM ANALYTICS.DIM_CUSTOMERS
UNION ALL SELECT 'dim_products', COUNT(*) FROM ANALYTICS.DIM_PRODUCTS
UNION ALL SELECT 'dim_sellers', COUNT(*) FROM ANALYTICS.DIM_SELLERS
UNION ALL SELECT 'dim_date', COUNT(*) FROM ANALYTICS.DIM_DATE;

-- REVENUE RECONCILIATION (DIFFERENCE MUST BE 0)
SELECT (SELECT SUM(PRICE) FROM RAW.ORDER_ITEMS)
     - (SELECT SUM(PRICE) FROM ANALYTICS.FACT_ORDER_ITEMS) AS ITEM_REVENUE_DIFF,
       (SELECT SUM(ITEMS_REVENUE) FROM ANALYTICS.FACT_ORDERS)
     - (SELECT SUM(PRICE) FROM ANALYTICS.FACT_ORDER_ITEMS) AS ORDER_VS_ITEM_DIFF;

-- 3. NO REVIEW DUPLICATION: SHOULD RETURN 0 ROWS
SELECT ORDER_ID, COUNT(*) FROM ANALYTICS.FACT_ORDERS
GROUP BY ORDER_ID HAVING COUNT(*) > 1;

